import { test, expect, request as contexts } from '@playwright/test';
import { register, post } from './helpers';
test('C08 private idempotent saves, two-account isolation and information reports',async({request:api,page})=>{
 test.setTimeout(60000);
 const list=await(await api.get('/api/v1/opportunities')).json();const id=list.items[0].id;
 expect((await api.get('/api/v1/me/saved')).status()).toBe(401);
 await register(api,'owner-a');
 const csrf=await(await api.get('/api/v1/auth/csrf')).json();
 expect((await api.put('/api/v1/me/saved/'+id)).status()).toBe(400);
 const responses=await Promise.all([1,2,3].map(()=>api.put('/api/v1/me/saved/'+id,{headers:{'X-CSRF-TOKEN':csrf.token}})));
 responses.forEach(r=>expect(r.status()).toBe(204));
 expect(await(await api.get('/api/v1/me/saved')).json()).toHaveLength(1);
 const other=await contexts.newContext({baseURL:'http://127.0.0.1:5173'});
 await register(other,'owner-b');
 expect(await(await other.get('/api/v1/me/saved')).json()).toHaveLength(0);
 const otherCsrf=await(await other.get('/api/v1/auth/csrf')).json();
 expect((await other.delete('/api/v1/me/saved/'+id,{headers:{'X-CSRF-TOKEN':otherCsrf.token}})).status()).toBe(204);
 expect(await(await api.get('/api/v1/me/saved')).json()).toHaveLength(1);
 expect((await post(other,'/api/v1/me/reports/'+id,{message:' '})).status()).toBe(400);
 expect((await post(other,'/api/v1/me/reports/'+id,{message:'Please verify the published closing date.'})).status()).toBe(200);
 expect((await other.get('/api/v1/editor/reports')).status()).toBe(403);
 await page.context().addCookies((await api.storageState()).cookies);
 await page.goto('/saved');await expect(page.getByRole('article')).toHaveCount(1);
 await page.getByRole('link',{name:list.items[0].title,exact:true}).click();
 await page.getByText('Report incorrect information',{exact:true}).click();
 await page.getByRole('button',{name:'Send report'}).click();
 await expect(page.getByText('Describe what seems incorrect.',{exact:true})).toBeVisible();
 await page.getByLabel('What should the editor check?').fill('Browser report: please recheck the source wording.');
 await page.getByRole('button',{name:'Send report'}).click();
 await expect(page.getByText('Report received. Thank you for helping improve the catalogue.')).toBeVisible();
 await page.getByRole('button',{name:'Remove from shortlist',exact:true}).click();
 await expect(page.getByRole('button',{name:'Save opportunity',exact:true})).toBeVisible();
 expect(await(await api.get('/api/v1/me/saved')).json()).toHaveLength(0);
 expect((await api.delete('/api/v1/me/saved/'+id,{headers:{'X-CSRF-TOKEN':csrf.token}})).status()).toBe(204);
 await other.dispose();
});
